export const DESKTOP_PLANE_CATALOGS: Record<string, DesktopPlaneCatalog> = {
  en: DESKTOP_PLANE_EN,
  pt: DESKTOP_PLANE_PT,
};

/** Locale aliases collapse onto base plane catalogs before falling back to en. */
const PLANE_ALIASES: Record<string, string> = {
  'pt-br': 'pt',
  'pt-pt': 'pt',
};

function resolvePlaneAlias(locale: string): string | null {
  const normalized = locale.toLowerCase();
  const alias = PLANE_ALIASES[normalized];
  if (alias && DESKTOP_PLANE_CATALOGS[alias]) return alias;
  if (DESKTOP_PLANE_CATALOGS[normalized]) return normalized;
  const base = normalized.split('-')[0];
  if (DESKTOP_PLANE_CATALOGS[base]) return base;
  return null;
}

/** Resolve one desktop plane string; returns null when the locale lacks it. */
export function lookupDesktopPlaneString(locale: string, key: string): string | null {
  const resolved = resolvePlaneAlias(locale);
  if (!resolved) return null;
  return DESKTOP_PLANE_CATALOGS[resolved][key] ?? null;
}

/** Register a hydrated catalog produced by the on-demand translation runtime. */
export function registerHydratedDesktopPlane(locale: string, catalog: DesktopPlaneCatalog): void {
  const normalized = locale.toLowerCase();
  const existing = DESKTOP_PLANE_CATALOGS[normalized] || {};
  DESKTOP_PLANE_CATALOGS[normalized] = { ...existing, ...catalog };
}
