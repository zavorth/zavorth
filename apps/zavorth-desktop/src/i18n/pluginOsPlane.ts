function localeVariant(base: Catalog, tweak: Partial<Catalog>): Catalog {
  const out: Catalog = { ...base };
  for (const [key, value] of Object.entries(tweak)) {
    if (typeof value === 'string') out[key] = value;
  }
  return out;
}

