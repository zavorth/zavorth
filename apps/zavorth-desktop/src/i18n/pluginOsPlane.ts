export function resolveDesktopLocale(language?: string | null): string {
  if (language && String(language).trim()) {
    return String(language).trim().replace(/_/g, '-');
  }
  const envLocale =
    typeof globalThis !== 'undefined'
      ? (globalThis as { process?: { env?: Record<string, string | undefined> } }).process?.env
          ?.ZAVORTH_LOCALE
      : undefined;
  if (envLocale) {
    return String(envLocale).trim().replace(/_/g, '-');
  }
  if (typeof navigator !== 'undefined' && navigator.language) {
    return String(navigator.language).replace(/_/g, '-');
  }
  return 'en';
}

export function tPluginOs(key: string, language?: string | null): string {
  const tag = resolveDesktopLocale(language);
  const exact = PLUGIN_OS_PLANE_I18N[tag];
  if (exact?.[key]) return exact[key];
  const lang = tag.split('-')[0]?.toLowerCase() || 'en';
  const byLang = PLUGIN_OS_PLANE_I18N[lang];
  if (byLang?.[key]) return byLang[key];
  return en[key] || key;
}

