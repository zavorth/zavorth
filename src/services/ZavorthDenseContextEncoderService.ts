export type ZavorthDenseContextEncodingResult = {
  mimeType: 'image/png';
  encodedImageBase64: string;
  linesEncoded: number;
  digest: string;
  tokenEstimateSource: 'unavailable';
};

export class ZavorthDenseContextEncoderService {
  private readonly maxCanvasWidth: number;
  private readonly maxCanvasHeight: number;

  constructor(options: { maxCanvasWidth: number; maxCanvasHeight: number }) {
    this.maxCanvasWidth = options.maxCanvasWidth;
    this.maxCanvasHeight = options.maxCanvasHeight;
  }

  public async encodeTextToBitmap(text: string): Promise<ZavorthDenseContextEncodingResult> {
    const lines = text.split('\n');
    const maxLineLength = lines.reduce((max, line) => Math.max(max, line.length), 0);
    const requiredWidth = maxLineLength * CHAR_ADVANCE_X;
    const requiredHeight = lines.length * CHAR_ADVANCE_Y;

    if (requiredWidth > this.maxCanvasWidth || requiredHeight > this.maxCanvasHeight) {
      throw new Error(`Text does not fit the configured canvas (${this.maxCanvasWidth}x${this.maxCanvasHeight})`);
    }

    const rgba = Buffer.alloc(this.maxCanvasWidth * this.maxCanvasHeight * 4, 0xFF);

    for (let lineIndex = 0; lineIndex < lines.length; lineIndex += 1) {
      const line = lines[lineIndex];
      const baselineY = lineIndex * CHAR_ADVANCE_Y;
      for (let charIndex = 0; charIndex < line.length; charIndex += 1) {
        const glyph = glyphFor(line.charCodeAt(charIndex));
        this.drawGlyph(rgba, glyph, charIndex * CHAR_ADVANCE_X, baselineY);
      }
    }

    const png = this.encodePng(rgba);
    const digest = createHash('sha256').update(png).digest('hex');

    return {
      mimeType: 'image/png',
      encodedImageBase64: png.toString('base64'),
      linesEncoded: lines.length,
      digest,
      tokenEstimateSource: 'unavailable',
    };
  }

  private drawGlyph(rgba: Buffer, glyph: number[], originX: number, originY: number): void {
    for (let col = 0; col < FONT_GLYPH_WIDTH; col += 1) {
      const column = glyph[col] ?? 0;
      for (let row = 0; row < FONT_GLYPH_HEIGHT; row += 1) {
        if (((column >> row) & 1) !== 1) {
          continue;
        }
        const x = originX + col;
        const y = originY + row;
        if (x >= this.maxCanvasWidth || y >= this.maxCanvasHeight) {
          continue;
        }
        const offset = (y * this.maxCanvasWidth + x) * 4;
        rgba[offset] = 0;
        rgba[offset + 1] = 0;
        rgba[offset + 2] = 0;
        rgba[offset + 3] = 255;
      }
    }
  }

  private encodePng(rgba: Buffer): Buffer {
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(this.maxCanvasWidth, 0);
    ihdr.writeUInt32BE(this.maxCanvasHeight, 4);
    ihdr[8] = 8;
    ihdr[9] = 6;
    ihdr[10] = 0;
    ihdr[11] = 0;
    ihdr[12] = 0;

    const stride = this.maxCanvasWidth * 4;
    const raw = Buffer.alloc(this.maxCanvasHeight * (1 + stride));
    for (let y = 0; y < this.maxCanvasHeight; y += 1) {
      const target = y * (1 + stride);
      raw[target] = 0;
      rgba.copy(raw, target + 1, y * stride, (y + 1) * stride);
    }
    const idat = deflateSync(raw);
    const signature = Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);

    return Buffer.concat([
      signature,
      buildPngChunk('IHDR', ihdr),
      buildPngChunk('IDAT', idat),
      buildPngChunk('IEND', Buffer.alloc(0)),
    ]);
  }
}

function glyphFor(charCode: number): number[] {
  if (charCode >= 32 && charCode <= 126) {
    return FONT_5X7[charCode - 32];
  }
  return BLOCK_GLYPH;
}

function buildPngChunk(type: string, data: Buffer): Buffer {
  const chunk = Buffer.alloc(12 + data.length);
  chunk.writeUInt32BE(data.length, 0);
  chunk.write(type, 4, 'ascii');
  data.copy(chunk, 8);
  const crc = computeCrc32(chunk.subarray(4, 8 + data.length));
  chunk.writeUInt32BE(crc, 8 + data.length);
  return chunk;
}

function computeCrc32(buffer: Buffer): number {
  let crc = 0xFFFFFFFF;
  for (let i = 0; i < buffer.length; i += 1) {
    crc ^= buffer[i];
    for (let bit = 0; bit < 8; bit += 1) {
      crc = (crc >>> 1) ^ ((crc & 1) === 1 ? 0xEDB88320 : 0);
    }
  }
  return (crc ^ 0xFFFFFFFF) >>> 0;
}
